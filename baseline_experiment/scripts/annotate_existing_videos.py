#!/usr/bin/env python3
"""
Annotate existing generated videos with CONDITIONING / GENERATED labels.

The saved videos from run_delta_a.py (and similar scripts) contain ALL frames:
the first `num_cond_frames` are conditioning frames (passed through VAE
encode/decode), and the rest are generated by the model.

This script adds:
  - GREEN border + "CONDITIONING" label to the first num_cond_frames frames
  - RED border   + "GENERATED"    label to the remaining frames

Usage (annotate a directory of videos):
  python annotate_existing_videos.py \
      --gen-dir ~/Downloads/generated_video/.../adasteer_bare_10step_g4/videos \
      --out-dir ~/Downloads/generated_video/.../adasteer_bare_10step_g4/annotated \
      --num-cond-frames 14

Usage (also prepend ground-truth conditioning from original dataset):
  python annotate_existing_videos.py \
      --gen-dir ~/Downloads/generated_video/.../notta_baseline_g4/videos \
      --orig-dir ~/Downloads/generated_video/.../gt_panda_source/videos \
      --out-dir ~/Downloads/generated_video/.../notta_baseline_g4/annotated \
      --num-cond-frames 14
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont


# ---------------------------------------------------------------------------
# Annotation helpers
# ---------------------------------------------------------------------------

def _get_font(size: int):
    for path in (
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/System/Library/Fonts/Helvetica.ttc",
        "/System/Library/Fonts/SFNSMono.ttf",
    ):
        try:
            return ImageFont.truetype(path, size)
        except (IOError, OSError):
            continue
    return ImageFont.load_default()


def annotate_frame(
    frame_uint8: np.ndarray,
    label: str,
    border_color: tuple[int, int, int] | None = None,
    border_width: int = 4,
) -> np.ndarray:
    img = Image.fromarray(frame_uint8)
    draw = ImageDraw.Draw(img)
    h, w = frame_uint8.shape[:2]

    if border_color is not None:
        for i in range(border_width):
            draw.rectangle([i, i, w - 1 - i, h - 1 - i], outline=border_color)

    font_size = max(14, h // 22)
    font = _get_font(font_size)
    margin = (border_width + 5) if border_color else 6
    bbox = draw.textbbox((margin, margin), label, font=font)
    pad = 4
    draw.rectangle(
        [bbox[0] - pad, bbox[1] - pad, bbox[2] + pad, bbox[3] + pad],
        fill=(0, 0, 0),
    )
    draw.text((margin, margin), label, fill="white", font=font)
    return np.array(img)


# ---------------------------------------------------------------------------
# Video I/O (using av)
# ---------------------------------------------------------------------------

def read_video_frames(path: str, max_frames: int = 999) -> list[np.ndarray]:
    """Read up to max_frames from a video, returning list of uint8 (H,W,3)."""
    import av
    container = av.open(path)
    frames = []
    for frame in container.decode(video=0):
        frames.append(frame.to_ndarray(format="rgb24"))
        if len(frames) >= max_frames:
            break
    container.close()
    return frames


def save_video(frames: list[np.ndarray], path: str, fps: int = 24):
    """Save list of uint8 (H,W,3) frames as mp4."""
    import torch
    from torchvision.io import write_video
    tensor = torch.from_numpy(np.stack(frames))
    write_video(path, tensor, fps=fps, video_codec="libx264",
                options={"crf": "18"})


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    p = argparse.ArgumentParser(
        description="Annotate generated videos with CONDITIONING/GENERATED labels.")
    p.add_argument("--gen-dir", type=str, required=True,
                   help="Directory with generated .mp4 files")
    p.add_argument("--orig-dir", type=str, default=None,
                   help="(Optional) Directory with original source .mp4 files. "
                        "If provided, a GT label track is also shown.")
    p.add_argument("--out-dir", type=str, required=True,
                   help="Output directory for annotated videos")
    p.add_argument("--num-cond-frames", type=int, default=14,
                   help="Number of conditioning frames in the generated video "
                        "(default: 14 for LongCat standard config)")
    p.add_argument("--fps", type=int, default=24)
    args = p.parse_args()

    gen_dir = Path(args.gen_dir)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    gen_videos = sorted(gen_dir.glob("*.mp4"))
    if not gen_videos:
        print(f"No .mp4 files found in {gen_dir}")
        sys.exit(1)

    print(f"Found {len(gen_videos)} generated videos")
    print(f"Conditioning frames: first {args.num_cond_frames}")
    print(f"Output: {out_dir}\n")

    for vp in gen_videos:
        print(f"  {vp.name} ...", end="", flush=True)

        all_frames = read_video_frames(str(vp))
        n_total = len(all_frames)

        if n_total <= args.num_cond_frames:
            print(f" SKIP (only {n_total} frames, need >{args.num_cond_frames})")
            continue

        annotated = []
        for i, f in enumerate(all_frames):
            if i < args.num_cond_frames:
                annotated.append(annotate_frame(
                    f, "CONDITIONING",
                    border_color=(0, 200, 0), border_width=4))
            else:
                annotated.append(annotate_frame(
                    f, "GENERATED",
                    border_color=(220, 0, 0), border_width=4))

        out_path = out_dir / vp.name
        save_video(annotated, str(out_path), fps=args.fps)
        print(f" -> {out_path.name} "
              f"({args.num_cond_frames} cond + "
              f"{n_total - args.num_cond_frames} gen = {n_total} frames)")

    print(f"\nDone. Annotated videos in: {out_dir}")


if __name__ == "__main__":
    main()
