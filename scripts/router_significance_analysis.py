#!/usr/bin/env python3
"""Significance / "is it just randomness?" analysis for the budget-grid router.

Answers three precise forms of "is the 12-config (and 13-action) router winning
from randomness, and is the oracle headroom real?":

  (1) Is the router's realized gain > 0 beyond sampling noise?
      -> paired bootstrap 95% CI + sign-flip permutation p-value on the per-video
         paired deltas d_i = realized(router_i) - fixed_i (and vs NO-TTA).

  (2) Does the router beat *random targeting*?  Two nulls:
        - random_pick   : uniform-random valid config per video (13-action also
                          allows the NO-TTA action). "Better than a coin flip?"
        - shuffle_picks : keep the EXACT multiset of the router's own picks (so
                          the config-usage marginal is identical) but permute
                          WHICH video gets which pick. Any gain above this null
                          is genuine per-video adaptivity, not just a good
                          average config choice. This is the sharpest test.
      Plus argmax match-rate vs the 1/k chance floor (binomial).

  (3) Is the oracle headroom real signal or "max over noise"?
      -> parametric noise-floor simulation: assume all configs are truly equal
         per video and differ only by Gaussian measurement noise with sigma
         estimated from the observed across-config spread; simulate the
         resulting max-over-k minus fixed. If the observed oracle headroom is
         within this noise-floor band, the oracle is essentially unroutable
         max-over-noise (consistent with the routability R^2 <= 0 diagnostic).

Router picks are the SAME leakage-free 5-fold OOF ridge picks as
run_router_full_matrix.py (imported primitives), so the numbers line up with the
reported router matrix. Offline: reuses cached per-config metrics + features, no
generation, no GPU.

Usage:
    python3 scripts/router_significance_analysis.py \
      --series-root sweep_experiment/results/panda_ood_budget_1000v_preview \
      --feature-date sweep_experiment/reports/per_video_analysis/2026-07-12 \
      --output-dir sweep_experiment/reports/per_video_analysis/2026-07-31/router_significance \
      --metrics psnr vbench --blocks A+B+C --actions 12 13
"""
