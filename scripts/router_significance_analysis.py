def paired_bootstrap_ci(
    d: np.ndarray, *, n_boot: int, seed: int, ci: float = 95.0
) -> Tuple[float, float, float]:
    """Percentile bootstrap CI for mean(d) (paired resample of videos)."""
    d = np.asarray(d, dtype=float)
    d = d[np.isfinite(d)]
    if d.size == 0:
        return float("nan"), float("nan"), float("nan")
    rng = np.random.default_rng(seed)
    n = d.size
    means = np.empty(n_boot, dtype=float)
    for b in range(n_boot):
        means[b] = d[rng.integers(0, n, n)].mean()
    lo = float(np.percentile(means, (100 - ci) / 2))
    hi = float(np.percentile(means, 100 - (100 - ci) / 2))
    return float(d.mean()), lo, hi


def sign_flip_p(d: np.ndarray, *, n_perm: int, seed: int) -> float:
    """Two-sided sign-flip permutation p for H0: mean(d) = 0.

    Under H0 (paired deltas symmetric about 0), the sign of each d_i is
    exchangeable; the null distribution of the mean is generated by random
    sign flips. Returns the two-sided p-value.
    """
    d = np.asarray(d, dtype=float)
    d = d[np.isfinite(d)]
    if d.size == 0:
        return float("nan")
    obs = abs(float(d.mean()))
    rng = np.random.default_rng(seed)
    n = d.size
    cnt = 0
    for _ in range(n_perm):
        signs = rng.integers(0, 2, n) * 2 - 1
        if abs(float((d * signs).mean())) >= obs:
            cnt += 1
    return (cnt + 1) / (n_perm + 1)


def _row_finite_choice(row: np.ndarray, rng: np.random.Generator) -> int:
    """Uniformly pick a column index among the finite entries of *row*."""
    fin = np.where(np.isfinite(row))[0]
    if fin.size == 0:
        return -1
    return int(fin[rng.integers(0, fin.size)])


def random_pick_null(
    Y_use: np.ndarray, fixedm: np.ndarray, *, n_draw: int, seed: int
) -> np.ndarray:
    """Null distribution of mean(realized - fixed) for a uniform-random picker.

    Y_use is n x K (K=12 for 12-action, 13 with the NO-TTA column appended).
    Each draw picks, per video, a uniformly random valid (finite) column.
    """
    rng = np.random.default_rng(seed)
    n = Y_use.shape[0]
    gains = np.empty(n_draw, dtype=float)
    for b in range(n_draw):
        realized = np.full(n, np.nan, dtype=float)
        for i in range(n):
            j = _row_finite_choice(Y_use[i], rng)
            if j >= 0:
                realized[i] = Y_use[i, j]
        gains[b] = _nanmean(realized - fixedm)
    return gains


def shuffle_picks_null(
    Y_use: np.ndarray,
    pick: np.ndarray,
    fixedm: np.ndarray,
    *,
    n_draw: int,
    seed: int,
) -> Tuple[np.ndarray, np.ndarray]:
    """Null where the router's own picks are permuted across videos.

    Keeps the exact multiset of picks (identical config-usage marginal) but
    randomizes which video receives which pick. Returns (null_gains, valid_mask)
    where valid_mask marks videos with a real pick used for the matched observed
    gain. Any observed gain above this null is per-video targeting signal.
    """
    valid = pick >= 0
    idx = np.where(valid)[0]
    picks_valid = pick[idx].astype(int)
    rng = np.random.default_rng(seed)
    gains = np.empty(n_draw, dtype=float)
    for b in range(n_draw):
        perm = rng.permutation(picks_valid)
        realized = np.full(len(pick), np.nan, dtype=float)
        for r, i in enumerate(idx):
            j = perm[r]
            if 0 <= j < Y_use.shape[1] and np.isfinite(Y_use[i, j]):
                realized[i] = Y_use[i, j]
        gains[b] = _nanmean(realized[valid] - fixedm[valid])
    return gains, valid


def oracle_noise_floor(
    Ym: np.ndarray, fixed_col: int, *, n_sim: int, seed: int
) -> Tuple[float, float, float, float]:
    """Parametric 'max-over-noise' null for the config-oracle headroom.

    Model: for each video i the K configs have the SAME true value mu_i and
    differ only by i.i.d. Gaussian noise with std sigma_i estimated from the
    observed across-config spread for that video. Simulate K noisy configs,
    take max - (the fixed column's noisy draw), average over videos. This is
    the oracle headroom you'd expect if configs carry no per-video signal.

    Returns (mean, lo95, hi95, mean_sigma). NOTE sigma_i estimated from the same
    values slightly *over*-states real signal (so this null is conservative:
    if the observed headroom is still <= this floor, it is squarely noise).
    """
    rng = np.random.default_rng(seed)
    n, k = Ym.shape
    # per-video mean/std over finite configs
    mu = np.full(n, np.nan)
    sig = np.full(n, np.nan)
    for i in range(n):
        row = Ym[i][np.isfinite(Ym[i])]
        if row.size >= 2:
            mu[i] = row.mean()
            sig[i] = row.std(ddof=1)
    ok = np.isfinite(mu) & np.isfinite(sig)
    mu_ok, sig_ok = mu[ok], sig[ok]
    m = mu_ok.size
    if m == 0:
        return float("nan"), float("nan"), float("nan"), float("nan")
    sims = np.empty(n_sim, dtype=float)
    fc = int(fixed_col)
    for b in range(n_sim):
        noise = rng.standard_normal((m, k)) * sig_ok[:, None]
        vals = mu_ok[:, None] + noise
        head = vals.max(axis=1) - vals[:, fc]
        sims[b] = float(head.mean())
    return (
        float(sims.mean()),
        float(np.percentile(sims, 2.5)),
        float(np.percentile(sims, 97.5)),
        float(np.nanmean(sig_ok)),
    )


def _one_sided_p(null: np.ndarray, observed: float) -> float:
    """P(null gain >= observed): how often random targeting matches/beats it."""
    null = null[np.isfinite(null)]
    if null.size == 0 or not math.isfinite(observed):
        return float("nan")
    return float((np.sum(null >= observed) + 1) / (null.size + 1))


